"""Checks the real IEEE PHM 2012 PRONOSTIA RUL benchmark.

These are genuine run-to-failure bearing recordings from FEMTO-ST, not our
motor. The tests guard provenance, causal feature construction, bearing-disjoint
validation and the measured benchmark metrics. They do not claim field
validation of remaining life on our rig.
"""

import hashlib
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "ml"))

import rul_pronostia as rul  # noqa: E402

RAW_DIR = os.path.join(ROOT, "data", "pronostia")
MANIFEST_PATH = os.path.join(RAW_DIR, "manifest.json")
REPORT_PATH = os.path.join(ROOT, "ml", "rul_pronostia_report.json")

# Filled from the committed, reproducible report generated by
# `python3 ml/rul_pronostia.py`. Tolerances allow only floating-point noise.
EXPECTED_LAST_RMSE_S = 335.2577590868679
EXPECTED_LAST_MAE_S = 182.90964285714287
EXPECTED_ALL_RMSE_S = 9557.013964835096
EXPECTED_ALL_MAE_S = 6656.679037440501
EXPECTED_BASELINE_RMSE_S = 8902.246907382429
EXPECTED_N_WINDOWS = 7480


def _write_fixture(directory: str, window: int = 4) -> None:
    """Small six-bearing fixture with the real PRONOSTIA CSV column layout."""

    root = Path(directory)
    for bearing in rul.BEARINGS:
        path = root / bearing
        path.mkdir()
        for index in range(window + 3):
            with open(path / f"acc_{index + 1:05d}.csv", "w") as handle:
                for sample in range(8):
                    handle.write(
                        f"0,0,{index * 10},{sample * 39000},"
                        f"{0.1 + index / 20 + sample / 1000},"
                        f"{0.2 + index / 30 - sample / 2000}\n"
                    )
        for index in range(2):
            with open(path / f"temp_{index + 1:05d}.csv", "w") as handle:
                for sample in range(4):
                    handle.write(
                        f"0,0,{index * 30},{sample},{70.0 + index + sample / 10}\n"
                    )


class PronostiaProvenanceTest(unittest.TestCase):
    def test_manifest_and_vendored_files_match(self):
        with open(MANIFEST_PATH, encoding="utf-8") as handle:
            manifest = json.load(handle)
        self.assertEqual(manifest["source"]["archive_md5"], rul.ARCHIVE_MD5)
        self.assertTrue(manifest["files"])
        for relative, expected in manifest["files"].items():
            with self.subTest(file=relative):
                path = os.path.join(RAW_DIR, relative)
                with open(path, "rb") as source:
                    actual = hashlib.md5(source.read()).hexdigest()
                self.assertEqual(actual, expected)

    def test_source_metadata_is_cited_and_not_field_validated(self):
        self.assertEqual(rul.LICENSED_COPY_DOI, "10.6084/m9.figshare.30595484.v1")
        self.assertEqual(rul.LICENSED_COPY_LICENSE, "CC BY 4.0")
        self.assertIn("not our motor", rul.LABEL)
        self.assertIn("not field-validated", rul.LABEL)
        self.assertEqual(len(rul.BEARINGS), 6)
        self.assertTrue(
            set(rul.BEARINGS).issubset(
                {
                    "Bearing1_1",
                    "Bearing1_2",
                    "Bearing2_1",
                    "Bearing2_2",
                    "Bearing3_1",
                    "Bearing3_2",
                }
            )
        )


class PronostiaFeatureTest(unittest.TestCase):
    def test_trailing_features_never_read_future_rows(self):
        sequence = np.arange(40, dtype=float).reshape(20, 2)
        full = rul._trailing_features(sequence, window=5)
        truncated = rul._trailing_features(sequence[:12], window=5)
        np.testing.assert_allclose(full[: truncated.shape[0]], truncated)

    def test_future_temperature_file_does_not_change_past_features(self):
        with tempfile.TemporaryDirectory() as tmp:
            _write_fixture(tmp, window=4)
            path = os.path.join(tmp, "Bearing1_1")
            before = rul.load_bearing(Path(path), window=4)
            with open(os.path.join(path, "temp_99999.csv"), "w") as handle:
                for sample in range(4):
                    handle.write(f"0,0,55,{sample},999.0\n")
            after = rul.load_bearing(Path(path), window=4)
            # The late-added file has a much larger recording number, so its
            # timestamp is after every vibration burst and it must be ignored.
            np.testing.assert_allclose(before.features, after.features)

    def test_labels_are_seconds_to_the_final_vibration_burst(self):
        with tempfile.TemporaryDirectory() as tmp:
            _write_fixture(tmp, window=4)
            data = rul.load_dataset(tmp, window=4)
            for bearing in rul.BEARINGS:
                with self.subTest(bearing=bearing):
                    item = data[bearing]
                    self.assertEqual(item.rul_s[-1], 0.0)
                    self.assertTrue(np.all(np.diff(item.rul_s) < 0))
                    self.assertLess(item.rul_s[0], item.duration_s)
                    self.assertEqual(item.features.shape[1], rul.N_FEATURES)

    def test_raw_dataset_contains_only_the_six_learning_bearings(self):
        with tempfile.TemporaryDirectory() as tmp:
            _write_fixture(tmp, window=4)
            os.makedirs(os.path.join(tmp, "Bearing9_9"))
            with self.assertRaises(ValueError):
                rul.load_dataset(tmp, window=4)


class PronostiaBenchmarkTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        with open(REPORT_PATH, encoding="utf-8") as handle:
            cls.committed = json.load(handle)
        cls.report = rul.evaluate(RAW_DIR)

    def test_report_is_reproducible_and_honestly_labelled(self):
        for key in ("status", "label", "source", "method", "data"):
            self.assertEqual(self.report[key], self.committed[key])
        for key in ("last_window", "all_windows", "constant_baseline_last_window"):
            for field, value in self.committed[key].items():
                with self.subTest(section=key, field=field):
                    if isinstance(value, (int, float)):
                        self.assertAlmostEqual(
                            self.report[key][field], value, delta=1.0
                        )
                    else:
                        self.assertEqual(self.report[key][field], value)
        for bearing, expected in self.committed["per_bearing"].items():
            actual = self.report["per_bearing"][bearing]
            self.assertEqual(actual["condition"], expected["condition"])
            self.assertEqual(actual["acc_files"], expected["acc_files"])
            self.assertEqual(actual["temp_files"], expected["temp_files"])
            for field in ("duration_s", "predicted_last_rul_s", "baseline_last_rul_s"):
                self.assertAlmostEqual(actual[field], expected[field], delta=1.0)
        self.assertIn("not our motor", self.report["label"])
        self.assertIn("not field-validated", self.report["label"])
        self.assertIs(self.report["source"]["our_motor"], False)
        self.assertIs(self.report["source"]["field_validation"], False)
        self.assertIn(
            "[NEED: explicit FEMTO-ST dataset licence]",
            self.report["source"]["explicit_femto_license"],
        )

    def test_validation_leaves_one_whole_bearing_out(self):
        self.assertEqual(list(self.report["per_bearing"]), list(rul.BEARINGS))
        self.assertEqual(
            self.report["method"]["validation"],
            "leave-one-bearing-out; all windows of the held bearing",
        )
        self.assertEqual(self.report["last_window"]["n_bearings"], 6)

    def test_measured_metrics_are_reproduced(self):
        last = self.report["last_window"]
        windows = self.report["all_windows"]
        baseline = self.report["constant_baseline_last_window"]
        self.assertEqual(windows["n_windows"], EXPECTED_N_WINDOWS)
        self.assertAlmostEqual(last["rmse_s"], EXPECTED_LAST_RMSE_S, delta=1.0)
        self.assertAlmostEqual(last["mae_s"], EXPECTED_LAST_MAE_S, delta=1.0)
        self.assertAlmostEqual(windows["rmse_s"], EXPECTED_ALL_RMSE_S, delta=1.0)
        self.assertAlmostEqual(windows["mae_s"], EXPECTED_ALL_MAE_S, delta=1.0)
        self.assertAlmostEqual(baseline["rmse_s"], EXPECTED_BASELINE_RMSE_S, delta=1.0)
        self.assertLess(last["rmse_s"], baseline["rmse_s"])


class PronostiaCliTest(unittest.TestCase):
    def test_cli_writes_json_report_from_small_fixture(self):
        script = os.path.join(ROOT, "ml", "rul_pronostia.py")
        with tempfile.TemporaryDirectory() as tmp:
            _write_fixture(tmp, window=4)
            report_path = os.path.join(tmp, "report.json")
            proc = subprocess.run(
                [
                    sys.executable,
                    script,
                    "--raw-dir",
                    tmp,
                    "--report",
                    report_path,
                    "--window",
                    "4",
                ],
                capture_output=True,
                text=True,
            )
            self.assertEqual(proc.returncode, 0, proc.stderr)
            with open(report_path, encoding="utf-8") as handle:
                written = json.load(handle)
            printed = json.loads(proc.stdout)
        self.assertEqual(written, printed)
        self.assertEqual(written["status"], "benchmark_complete")
        self.assertEqual(written["all_windows"]["n_windows"], 24)
        self.assertIn("not field-validated", written["label"])

    def test_cli_rejects_missing_bearings(self):
        script = os.path.join(ROOT, "ml", "rul_pronostia.py")
        with tempfile.TemporaryDirectory() as tmp:
            proc = subprocess.run(
                [
                    sys.executable,
                    script,
                    "--raw-dir",
                    tmp,
                    "--report",
                    os.path.join(tmp, "report.json"),
                ],
                capture_output=True,
                text=True,
            )
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("ERROR", proc.stderr)


if __name__ == "__main__":
    unittest.main()
